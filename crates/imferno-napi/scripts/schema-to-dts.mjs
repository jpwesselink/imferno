// Converts the combined JSON Schema printed by imferno-core's
// `bindings_schema` example into a package's `types.d.ts`. Invoked by
// `cargo xtask generate-types-ts` (once for @imferno/node, once for
// @imferno/wasm) — do not run by hand.
//
// usage: node schema-to-dts.mjs <combined-schema.json> <out.d.ts>
import { readFileSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const [schemaPath, out] = process.argv.slice(2);
if (!schemaPath || !out) {
  console.error("usage: schema-to-dts.mjs <schema.json> <out.d.ts>");
  process.exit(1);
}

const schema = JSON.parse(readFileSync(schemaPath, "utf-8"));

// Normalise schemars output so every Rust type maps to exactly one named
// TypeScript declaration:
// - give each definition a `title` (json-schema-to-typescript names types by
//   title, so references resolve to the definition instead of being inlined);
// - reduce `$ref` nodes to a bare `$ref` (schemars attaches the field's doc
//   comment as a sibling `description`, which draft-07 ignores but which makes
//   json-schema-to-typescript emit a duplicate `Foo1` type per field), and
//   collapse `{ allOf: [{ $ref }], description }` wrappers the same way.
for (const [name, def] of Object.entries(schema.definitions ?? {})) {
  if (typeof def === "object" && def !== null && !def.title) def.title = name;
}
function collapseRefWrappers(node) {
  if (Array.isArray(node)) return node.map(collapseRefWrappers);
  if (typeof node !== "object" || node === null) return node;
  const keys = Object.keys(node);
  if (typeof node.$ref === "string") return { $ref: node.$ref };
  if (
    Array.isArray(node.allOf) &&
    node.allOf.length === 1 &&
    node.allOf[0].$ref &&
    keys.every((k) => k === "allOf" || k === "description" || k === "default")
  ) {
    return { $ref: node.allOf[0].$ref };
  }
  const out = {};
  for (const k of keys) out[k] = collapseRefWrappers(node[k]);
  return out;
}
const normalised = cleanDocs(collapseRefWrappers(schema));

// Rustdoc → JSDoc: drop fenced (Rust) code examples, which schemars flattens
// onto one line and json-schema-to-typescript mangles (`*/` → `* /`), and
// unwrap intra-doc links ([`Foo`](crate::x) / [`Foo`] → `Foo`).
function cleanDocText(text) {
  return text
    .replace(/```[\s\S]*?```/g, "")
    // Labels whose code example was just removed ("Before:"), then headings
    // left with an empty section.
    .replace(/^[A-Za-z ]+:[ \t]*$/gm, "")
    .replace(/^#+ .*\n(?=\s*(?:#|(?![\s\S])))/gm, "")
    .replace(/\[(`[^`\]]+`)\]\([^)]*\)/g, "$1")
    .replace(/\[(`[^`\]]+`)\]/g, "$1")
    .replace(/[ \t]+\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}
function cleanDocs(node) {
  if (Array.isArray(node)) return node.map(cleanDocs);
  if (typeof node !== "object" || node === null) return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    out[k] = (k === "description" || k === "deprecated") && typeof v === "string" ? cleanDocText(v) : cleanDocs(v);
  }
  return out;
}

const banner = `/**
 * TypeScript declarations for the values imferno passes across the JS boundary.
 *
 * Auto-generated by \`cargo xtask generate-types-ts\` from the Rust types'
 * JSON Schema (schemars) — do not edit. @imferno/node and @imferno/wasm each
 * ship their own copy: the WASM build serialises some CPL fields in camelCase.
 */`;

let dts = await compile(normalised, "ImfernoTypes", {
  bannerComment: banner,
  // Rust structs are closed: never emit `[k: string]: unknown` catch-alls.
  additionalProperties: false,
  // Emit every definition, even ones only reachable through the container.
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  format: true,
  style: { singleQuote: false, semi: true, printWidth: 100 },
});

// The container interface exists only to give every root type a reference
// path; it is not a runtime value, so drop it from the public surface.
dts = dts.replace(/\/\*\*\n \* Container for every type[\s\S]*?\nexport interface ImfernoTypes \{[\s\S]*?\n\}\n/, "");
if (dts.includes("interface ImfernoTypes")) {
  throw new Error("failed to strip ImfernoTypes container from generated output");
}
// Drop json-schema-to-typescript's provenance boilerplate from doc comments.
dts = dts
  .replace(/\n \*\n \* This interface was referenced by `ImfernoTypes`'s JSON-Schema\n \* via the `definition` "[^"]+"\./g, "")
  .replace(/\/\*\*\n \* This interface was referenced by `ImfernoTypes`'s JSON-Schema\n \* via the `definition` "[^"]+"\.\n \*\/\n/g, "");
if (dts.includes("This interface was referenced by")) {
  throw new Error("failed to strip json-schema-to-typescript provenance comments");
}

// Input option types. The bindings parse options from a loose JS object
// (`crates/imferno-{napi,wasm}/src/lib.rs::parse_options`), so there is no Rust
// type to derive these from. They are guarded by the NAPI contract test
// (crates/imferno-napi/test/contract.test.mjs), which checks the declared keys
// against the keys each `parse_options` reads, and every declared spec literal
// and rule severity against the engine.
dts += `
/**
 * Core constraints (ST 2067-2) edition to validate against. \`"auto"\` detects
 * it from the package and CPLs. A pinned edition also pins the editions it
 * cites (ST 2067-3, ST 2067-201 for IAB, ST 377-1/377-4 for MXF), over the
 * documents' namespaces, unless \`cplSpec\` / \`iabSpec\` pin those separately.
 */
export type CoreSpec = "auto" | "v2013" | "v2016" | "v2020";

/**
 * Composition Playlist (ST 2067-3) edition to validate against; wins over the
 * edition \`coreSpec\` implies. ST 2067-3:2016 and :2020 share one namespace;
 * \`"auto"\` applies the newest unless the CPL uses something only one edition
 * defines, and reports the choice.
 */
export type CplSpec = "auto" | "v2013" | "v2016" | "v2020";

/**
 * IAB plug-in (ST 2067-201) edition to validate against; wins over the edition
 * \`coreSpec\` implies. Every edition shares one namespace; \`"auto"\` applies
 * the newest and reports the choice.
 */
export type IabSpec = "auto" | "v2019" | "v2021" | "v2026";

/**
 * App #2E (ST 2067-21) edition to validate against. \`"auto"\` uses the CPL's
 * ApplicationIdentification; \`"none"\` skips application-profile validation.
 */
export type App2eSpec = "auto" | "none" | "v2014" | "v2016" | "v2020" | "v2023" | "v2026";

/** Options accepted by every validating entry point. */
export interface ValidateOptions {
  /** Core constraints edition. Default: \`"auto"\`. */
  coreSpec?: CoreSpec;
  /** Composition Playlist (ST 2067-3) edition. Default: \`"auto"\`. */
  cplSpec?: CplSpec;
  /** IAB plug-in (ST 2067-201) edition. Default: \`"auto"\`. */
  iabSpec?: IabSpec;
  /** App #2E edition. Default: \`"auto"\`. */
  app2eSpec?: App2eSpec;
  /** ESLint-style per-rule severity overrides, keyed by code, rule suffix, glob or \`source:<kind>\`. */
  rules?: RulesConfig;
  /** Collapse repeated identical findings into one issue with \`additional_instances\`. Default: \`false\`. */
  aggregateRepeats?: boolean;
}
`;

writeFileSync(out, dts);
console.error(`  wrote ${out}`);
