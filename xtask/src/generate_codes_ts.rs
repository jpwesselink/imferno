//! Generates `codes.js` + `codes.d.ts` (WASM ESM, NAPI CJS) from the rule
//! catalogue.
//!
//! `codes.<SPEC>.<Name>` is the rule id (`"ST2067-3/SegmentDuration"`), a
//! valid `rules` key that selects the rule in every edition, with a literal
//! TypeScript type for autocomplete and typo protection. Spec keys replace
//! `-` with `_` (`ST2067_3`, `XSD`, `IMFERNO`).

use imferno_core::catalogue;

use std::fs;
use std::path::Path;

fn spec_key(id: &str) -> String {
    id.replace('-', "_")
}

/// `(spec key, [(rule name, rule id)])` per spec, in catalogue order.
fn groups() -> Vec<(String, Vec<(String, String)>)> {
    catalogue::tables()
        .into_iter()
        .map(|(spec, rules)| {
            let entries = rules
                .iter()
                .map(|r| (r.name().to_string(), r.id().0))
                .collect();
            (spec_key(spec.id()), entries)
        })
        .collect()
}

fn js_body() -> String {
    groups()
        .iter()
        .map(|(spec, entries)| {
            let mut out = format!("  {spec}: {{\n");
            for (name, id) in entries {
                out.push_str(&format!("    {name}: \"{id}\",\n"));
            }
            out.push_str("  }");
            out
        })
        .collect::<Vec<_>>()
        .join(",\n")
}

fn dts_body() -> String {
    groups()
        .iter()
        .map(|(spec, entries)| {
            let mut out = format!("  readonly {spec}: {{\n");
            for (name, id) in entries {
                out.push_str(&format!("    readonly {name}: \"{id}\";\n"));
            }
            out.push_str("  }");
            out
        })
        .collect::<Vec<_>>()
        .join(";\n")
}

pub fn run() {
    let workspace_root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask has a parent directory");

    const HEADER: &str =
        "// Auto-generated by `cargo xtask generate-codes-ts` \u{2014} do not edit.\n\
         // Rule ids (`SPEC/Name`), usable as `rules` keys; one per rule, all editions.\n";

    let js = format!("{HEADER}export const codes = {{\n{}\n}};\n", js_body());
    let dts = format!(
        "{HEADER}export declare const codes: {{\n{}\n}};\n",
        dts_body()
    );

    let wasm_dir = workspace_root.join("crates/imferno-wasm");
    for (name, body) in [("codes.js", &js), ("codes.d.ts", &dts)] {
        let path = wasm_dir.join(name);
        fs::write(&path, body).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
        println!("  wrote {}", path.display());
    }

    let napi_dir = workspace_root.join("crates/imferno-napi");
    let cjs = format!(
        "{HEADER}const codes = {{\n{}\n}};\nmodule.exports = {{ codes }};\n",
        js_body()
    );
    for (name, body) in [("codes.js", &cjs), ("codes.d.ts", &dts)] {
        let path = napi_dir.join(name);
        fs::write(&path, body).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
        println!("  wrote {}", path.display());
    }
}
